@router.get("/catalog")
async def get_items_catalog(
    slot_type: Optional[str] = Query(None, description="weapon, vitality, or spirit"),
    tier: Optional[int] = Query(None, description="1, 2, 3, or 4"),
) -> List[Dict[str, Any]]:
    """Returns curated Deadlock shop items catalog filtered by slot type and tier."""
    items = CURATED_ITEMS_CATALOG
    if slot_type:
        st = slot_type.lower().strip()
        items = [i for i in items if i["slot_type"] == st]
    if tier:
        items = [i for i in items if i["tier"] == tier]
    return items


