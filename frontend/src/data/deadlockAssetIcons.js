/**
 * Returns the official hero avatar image URL, or null if not found.
 */
export function getHeroIcon(heroName) {
  if (!heroName) return null;
  const cleanName = heroName.trim();
  if (HERO_ICONS[cleanName]) return HERO_ICONS[cleanName];

  const lower = cleanName.toLowerCase();
  for (const [key, url] of Object.entries(HERO_ICONS)) {
    if (key.toLowerCase() === lower) return url;
  }
  for (const [key, url] of Object.entries(HERO_ICONS)) {
    if (lower.includes(key.toLowerCase()) || key.toLowerCase().includes(lower)) return url;
  }
  return null;
}

/**
 * Returns the official in-game shop item icon URL, or null if not found.
 * Automatically handles parenthetical prefixes/suffixes such as "(1er Vitality !)" or "(15e Item)".
 */
export function getItemIcon(itemName) {
  if (!itemName) return null;
  const cleanName = itemName.replace(/\s*\([^)]*\)/g, '').trim();

  if (ITEM_ICONS[cleanName]) return ITEM_ICONS[cleanName];
  if (ITEM_ICONS[itemName]) return ITEM_ICONS[itemName];

  const lower = cleanName.toLowerCase();
  for (const [key, url] of Object.entries(ITEM_ICONS)) {
    if (key.toLowerCase() === lower) return url;
  }
  for (const [key, url] of Object.entries(ITEM_ICONS)) {
    if (lower.includes(key.toLowerCase()) || key.toLowerCase().includes(lower)) return url;
  }
  return null;
}
